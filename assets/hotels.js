export function hotelsInRegion(regionId) {
  return regionId && regionId !== "all" ? hotels.filter(h => h.region === regionId) : hotels.slice();
}

export function searchHotels(term, regionId) {
  const pool = hotelsInRegion(regionId);
  const q = (term || "").trim().toLowerCase();
  if (!q) return pool;
  const norm = s => s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  return pool.filter(h => norm(h.name).includes(norm(q)));
}

export function regionLabel(regionId, lang) {
  const r = hotelRegions.find(x => x.id === regionId);
  return r ? (r.label[lang] || r.label.fr) : regionId;
}

export function hotelDirectoryIsValid() {
  const ids = new Set();
  const regions = new Set(hotelRegions.map(r => r.id));
  if (hotelRegions.some(r => !r.id || !["fr", "en", "es"].every(l => r.label[l]))) return false;
  if (hotelRegions.some(r => r.count !== hotels.filter(h => h.region === r.id).length)) return false;
  return hotels.every(h => {
    if (!h.id || !h.name || ids.has(h.id)) return false;
    ids.add(h.id);
    return regions.has(h.region) && typeof h.confirmed === "boolean" && !!h.airport;
  });
}
